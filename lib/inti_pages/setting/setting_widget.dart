class ApiService {
  final String baseUrl = "http://172.20.10.5:3000";

  Future<Map<String, dynamic>> fetchThresholdData(
      String id, double minThreshold, double maxThreshold) async {
    final uri = Uri.parse(
        "$baseUrl/api/data/threshold/$id?minThreshold=$minThreshold&maxThreshold=$maxThreshold");

    try {
      final response = await http.get(uri);

      if (response.statusCode == 200) {
        return jsonDecode(response.body);
      } else {
        throw Exception(
            'Failed to load data. Status code: ${response.statusCode}');
      }
    } catch (e) {
      throw Exception('Failed to fetch data: $e');
    }
  }
}

